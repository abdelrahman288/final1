    /** أنسب فئة أذكار للوقت: صباح بعد الفجر لحد الظهر، مساء بعد العصر لحد العشاء. */
    static int suggestedCat(long now, long[] t) {
        if (now >= t[Prayer.FAJR] && now < t[Prayer.DHUHR]) return 0;
        if (now >= t[Prayer.ASR] && now < t[Prayer.ISHA] + 3600000L) return 1;
        return -1;
    }

    // ---------------- المناسبات ----------------

    /** يرجّع {عنوان، تفصيل} لأقرب مناسبة. */
    static String[] occasion(Calendar cal, int hadj) {
        int dow = cal.get(Calendar.DAY_OF_WEEK); // 1 أحد .. 6 جمعة .. 7 سبت
        int y = cal.get(Calendar.YEAR), m = cal.get(Calendar.MONTH) + 1, d = cal.get(Calendar.DAY_OF_MONTH);
        int[] h = Fmt.hijri(y, m, d, hadj);
        if (dow == Calendar.FRIDAY) return new String[]{"اليوم الجمعة", "سورة الكهف • أكثر من الصلاة على النبي ﷺ"};
        if (h[1] == 9) return new String[]{"رمضان كريم", "اليوم " + Fmt.digits(h[0]) + " من شهر رمضان"};
        if (h[1] == 12 && h[0] == 9) return new String[]{"يوم عرفة", "صيام يوم عرفة يكفّر سنتين"};
        if (h[1] == 12 && h[0] >= 10 && h[0] <= 13) return new String[]{"عيد الأضحى", "تقبّل الله طاعاتكم • أيام التشريق"};
        if (h[1] == 10 && h[0] <= 3) return new String[]{"عيد الفطر", "عيدكم مبارك"};
        if (h[0] >= 13 && h[0] <= 15) return new String[]{"الأيام البيض", "صيام ١٣ و١٤ و١٥ من كل شهر هجري"};
        if (h[1] == 1 && h[0] == 10) return new String[]{"يوم عاشوراء", "صيامه يكفّر سنة ماضية"};
        int toFri = (Calendar.FRIDAY - dow + 7) % 7;
        // أقرب مناسبة هجرية خلال 45 يوم
        String[][] ev = {{"9", "1", "رمضان"}, {"10", "1", "عيد الفطر"}, {"12", "9", "يوم عرفة"}, {"12", "10", "عيد الأضحى"}, {"1", "1", "رأس السنة الهجرية"}, {"1", "10", "يوم عاشوراء"}};
        int bestDays = 999;
        String bestName = null;
        for (int i = 1; i <= 45; i++) {
            Calendar c2 = (Calendar) cal.clone();
            c2.add(Calendar.DAY_OF_MONTH, i);
            int[] hh = Fmt.hijri(c2.get(Calendar.YEAR), c2.get(Calendar.MONTH) + 1, c2.get(Calendar.DAY_OF_MONTH), hadj);
            for (String[] e : ev) {
                if (hh[1] == Integer.parseInt(e[0]) && hh[0] == Integer.parseInt(e[1]) && i < bestDays) {
                    bestDays = i;
                    bestName = e[2];
                }
            }
        }
        if (bestName != null && bestDays < toFri + 30) {
            return new String[]{"مناسبة قادمة", bestName + " بعد " + days(bestDays)};
        }
        return new String[]{"مناسبة قادمة", "الجمعة " + (toFri == 1 ? "غداً" : "بعد " + days(toFri)) + " • سورة الكهف"};
    }

    private static String days(int n) {
        if (n == 1) return "يوم";
        if (n == 2) return "يومين";
        return Fmt.digits(n) + (n <= 10 ? " أيام" : " يوم");
    }
